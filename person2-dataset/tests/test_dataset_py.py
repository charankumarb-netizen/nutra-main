def run_all_tests():

    dataframe = load_dataset()

    tests_passed = 0
    tests_failed = 0

    tests = [
        (
            "Dataset exists",
            lambda: test_dataset_exists()
        ),
        (
            "Dataset loads",
            lambda: test_dataset_loads(
                dataframe
            )
        ),
        (
            "Dataset rows",
            lambda: test_dataset_rows(
                dataframe
            )
        ),
        (
            "Dataset columns",
            lambda: test_dataset_columns(
                dataframe
            )
        ),
        (
            "Required columns",
            lambda: test_required_columns(
                dataframe
            )
        ),
        (
            "Transcription column",
            lambda: test_transcription_column(
                dataframe
            )
        ),
        (
            "Medical specialty column",
            lambda: test_medical_specialty_column(
                dataframe
            )
        ),
        (
            "Duplicate rows",
            lambda: test_duplicate_rows(
                dataframe
            )
        ),
        (
            "Transcription missing values",
            lambda: test_transcription_missing_values(
                dataframe
            )
        ),
        (
            "Keywords missing values",
            lambda: test_keywords_missing_values(
                dataframe
            )
        ),
        (
            "Medical specialties",
            lambda: test_medical_specialties(
                dataframe
            )
        ),
    ]

    print()
    print("=" * 70)
    print("RUNNING TESTS")
    print("=" * 70)

    for name, test in tests:

        try:

            test()

            tests_passed += 1

        except Exception as error:

            tests_failed += 1

            print(
                f"FAIL: {name}"
            )

            print(
                f"Error: {error}"
            )

    # ========================================================
    # FINAL RESULT
    # ========================================================

    print()
    print("=" * 70)
    print("TEST SUMMARY")
    print("=" * 70)

    print(
        f"Tests passed: {tests_passed}"
    )

    print(
        f"Tests failed: {tests_failed}"
    )

    print(
        f"Total tests: "
        f"{len(tests)}"
    )

    print()

    if tests_failed == 0:

        print(
            "ALL TESTS PASSED"
        )

        print(
            "Person 2 dataset tests are successful."
        )

    else:

        print(
            "SOME TESTS FAILED"
        )


# ============================================================
# MAIN
# ============================================================

if __name__ == "__main__":

    run_all_tests()



